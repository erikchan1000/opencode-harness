#!/usr/bin/env python3
"""Merge omp/config.fragment.yml into an omp config.yml.

Usage: merge_config.py <fragment.yml> <target config.yml> [--extension-dir <abs path>]...

omp itself (/model UI, `omp config set`) writes the target file, so only the
keys the fragment owns are touched; everything else is preserved. The target
is backed up first. PyYAML rewrites the file, so YAML comments are lost (the
backup keeps them).

Owned: modelRoles (per role), modelPresets (per preset name, replaced whole),
task.maxRecursionDepth, task.isolation.enabled, bash.patterns (fragment entries first),
extensions (each --extension-dir appended when absent; user entries never removed).
"""
import copy
import shutil
import sys
from datetime import datetime
from pathlib import Path

import yaml


def load_mapping(path: Path) -> dict:
    data = yaml.safe_load(path.read_text())
    if data is None:
        return {}
    if not isinstance(data, dict):
        raise ValueError(f"{path}: expected a YAML mapping at top level, got {type(data).__name__}")
    return data


def _section(config: dict, key: str) -> dict:
    value = config.setdefault(key, {})
    if not isinstance(value, dict):
        raise ValueError(f"config key '{key}' must be a mapping, got {type(value).__name__}")
    return value


def merge(fragment: dict, current: dict, extension_dirs: tuple[str, ...] = ()) -> tuple[dict, list[str]]:
    """Return (merged config, human-readable change lines). Does not mutate inputs.

    The fragment is generated by omp/build.py and always carries every owned key.
    """
    merged = copy.deepcopy(current)
    changes: list[str] = []

    roles = _section(merged, "modelRoles")
    for role, model in fragment["modelRoles"].items():
        if roles.get(role) != model:
            changes.append(f"modelRoles.{role}: {roles.get(role)!r} -> {model!r}")
        roles[role] = model

    presets = _section(merged, "modelPresets")
    for name, preset in fragment["modelPresets"].items():
        if presets.get(name) != preset:
            changes.append(f"modelPresets.{name}: replaced")
        presets[name] = preset

    task = _section(merged, "task")
    depth = fragment["task"]["maxRecursionDepth"]
    if task.get("maxRecursionDepth") != depth:
        changes.append(f"task.maxRecursionDepth: {task.get('maxRecursionDepth')!r} -> {depth!r}")
    task["maxRecursionDepth"] = depth
    isolation = _section(task, "isolation")
    enabled = fragment["task"]["isolation"]["enabled"]
    if isolation.get("enabled") != enabled:
        changes.append(f"task.isolation.enabled: {isolation.get('enabled')!r} -> {enabled!r}")
    isolation["enabled"] = enabled

    bash = _section(merged, "bash")
    existing = bash.get("patterns", [])
    if not isinstance(existing, list):
        raise ValueError(f"config key 'bash.patterns' must be a list, got {type(existing).__name__}")
    owned = fragment["bash"]["patterns"]
    rest = [p for p in existing if p not in owned]
    new = owned + rest
    if new != existing:
        changes.append(f"bash.patterns: {len(owned)} owned entries placed first")
    bash["patterns"] = new

    if extension_dirs:
        extensions = merged.setdefault("extensions", [])
        if not isinstance(extensions, list):
            raise ValueError(f"config key 'extensions' must be a list, got {type(extensions).__name__}")
        for directory in extension_dirs:
            if directory not in extensions:
                extensions.append(directory)
                changes.append(f"extensions: added {directory}")

    return merged, changes


def main(argv: list[str]) -> int:
    args = argv[1:]
    extension_dirs: list[str] = []
    positional: list[str] = []
    while args:
        arg = args.pop(0)
        if arg == "--extension-dir":
            if not args:
                print(__doc__, file=sys.stderr)
                return 2
            directory = args.pop(0)
            if not Path(directory).is_absolute():
                raise ValueError(f"--extension-dir must be an absolute path, got {directory!r}")
            extension_dirs.append(directory)
        else:
            positional.append(arg)
    if len(positional) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    fragment_path, target = Path(positional[0]), Path(positional[1])
    fragment = load_mapping(fragment_path)

    if target.exists():
        current = load_mapping(target)  # raises on a malformed target before any write
    else:
        current = None

    merged, changes = merge(fragment, current or {}, tuple(extension_dirs))
    if current is not None and merged == current:
        print(f"  merged {fragment_path.name} into {target}")
        print("    (no changes)")
        return 0
    if current is None:
        print(f"  creating {target}")
    else:
        backup = target.with_name(f"{target.name}.bak-{datetime.now():%Y%m%d-%H%M%S}")
        shutil.copy2(target, backup)
        print(f"  backed up {target} -> {backup}")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(yaml.safe_dump(merged, sort_keys=False))
    print(f"  merged {fragment_path.name} into {target}")
    for line in changes:
        print(f"    {line}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
