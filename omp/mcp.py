#!/usr/bin/env python3
"""Convert the "mcp" block of opencode.jsonc into an omp `mcp.json`, and merge it.

Usage: mcp.py merge <generated mcp.json> <target mcp.json>

omp/mcp.json is GENERATED by omp/build.py from the `mcp` block of
opencode.jsonc (JSON cannot carry a header comment, so provenance is stated
here). Edit opencode.jsonc, then re-run `python3 omp/build.py`.

Secrets never enter the generated file (this repo is public). References are
rewritten, not resolved:
  {env:V}        -> "${V}"            (omp expands it at discovery)
  {file:/abs/p}  -> "!cat '/abs/p'"   (omp runs it when it starts the server;
                                       valid for stdio `env` values only)
  oauth clientId / clientSecret -> "${GOOGLE_SHEETS_MCP_CLIENT_ID}" /
                                   "${GOOGLE_SHEETS_MCP_CLIENT_SECRET}", because
                                   omp documents only `${VAR}` for `oauth`, not
                                   `!command`. EXPORT both variables before
                                   starting omp; their values are the contents of
                                   ~/.config/opencode/google-sheets-mcp-client-id
                                   and ...-client-secret. Sign in with
                                   `/mcp reauth google-sheets`.

`merge` is used by omp/install.sh. omp itself writes the target (`/mcp add`),
so a generated server is added only when its NAME is absent; an existing entry
is never modified, and servers the user added are kept.
"""
import copy
import json
import re
import shlex
import shutil
import sys
from datetime import datetime
from pathlib import Path

SCHEMA_URL = "https://raw.githubusercontent.com/can1357/oh-my-pi/main/packages/coding-agent/src/config/mcp-schema.json"

SERVER_KEYS = {"type", "url", "command", "env", "environment", "enabled", "oauth"}
OAUTH_KEYS = {"clientId", "clientSecret", "scope"}

# (server, oauth field) -> the environment variable the user exports.
OAUTH_ENV_VARS = {
    ("google-sheets", "clientId"): "GOOGLE_SHEETS_MCP_CLIENT_ID",
    ("google-sheets", "clientSecret"): "GOOGLE_SHEETS_MCP_CLIENT_SECRET",
}
OAUTH_SECRET_FIELDS = ("clientId", "clientSecret")

# server -> OAuth redirect URI. This is the redirect URI already registered on
# the GCP client for opencode (opencode's fixed MCP callback), so omp reuses it
# with no GCP console change. opencode and omp therefore cannot run the Sheets
# login at the same moment (both listen on this port).
REDIRECT_URIS = {"google-sheets": "http://127.0.0.1:19876/mcp/oauth/callback"}

_ENV_REF = re.compile(r"\{env:([A-Za-z_][A-Za-z0-9_]*)\}")
_FILE_REF = re.compile(r"\{file:([^}]+)\}")


def _where(server: str, key: str) -> str:
    return f"mcp.{server}.{key}"


def _env_value(server: str, key: str, value) -> str:
    where = _where(server, key)
    if not isinstance(value, str):
        raise ValueError(f"{where}: expected a string, got {type(value).__name__}")
    if m := _ENV_REF.fullmatch(value):
        return "${" + m.group(1) + "}"
    if m := _FILE_REF.fullmatch(value):
        path = m.group(1)
        if not path.startswith("/"):
            raise ValueError(f"{where}: {{file:}} path must be absolute, got {path!r}")
        return f"!cat {shlex.quote(path)}"
    if "{env:" in value or "{file:" in value:
        raise ValueError(f"{where}: reference token must be the whole value, got {value!r}")
    return value


def _oauth(server: str, oauth) -> dict:
    where = _where(server, "oauth")
    if not isinstance(oauth, dict):
        raise ValueError(f"{where}: expected an object, got {type(oauth).__name__}")
    unknown = sorted(set(oauth) - OAUTH_KEYS)
    if unknown:
        raise ValueError(f"{where}: unknown key(s) {unknown}")
    if server not in REDIRECT_URIS:
        raise ValueError(f"{where}: no redirect URI known for server {server!r}, add it to REDIRECT_URIS")
    out: dict = {}
    for field in OAUTH_SECRET_FIELDS:
        if field not in oauth:
            continue
        value = oauth[field]
        if not isinstance(value, str) or not (_ENV_REF.fullmatch(value) or _FILE_REF.fullmatch(value)):
            raise ValueError(f"{where}.{field}: must be an {{env:}} or {{file:}} reference, a literal would inline a secret")
        if (server, field) not in OAUTH_ENV_VARS:
            raise ValueError(f"{where}.{field}: no env var name known, add ({server!r}, {field!r}) to OAUTH_ENV_VARS")
        out[field] = "${" + OAUTH_ENV_VARS[(server, field)] + "}"
    if "scope" in oauth:
        out["scope"] = oauth["scope"]
    out["redirectUri"] = REDIRECT_URIS[server]
    return out


def _server(name: str, cfg) -> dict:
    if not isinstance(cfg, dict):
        raise ValueError(f"mcp.{name}: expected an object, got {type(cfg).__name__}")
    unknown = sorted(set(cfg) - SERVER_KEYS)
    if unknown:
        raise ValueError(f"mcp.{name}: unknown key(s) {unknown}")
    if "type" not in cfg:
        raise ValueError(f"mcp.{name}: missing 'type'")
    kind = cfg["type"]
    out: dict
    if kind == "remote":
        if "url" not in cfg:
            raise ValueError(f"mcp.{name}: remote server needs 'url'")
        if "command" in cfg:
            raise ValueError(f"mcp.{name}: remote server cannot have 'command'")
        out = {"type": "http", "url": cfg["url"]}
    elif kind == "local":
        command = cfg.get("command")
        if not isinstance(command, list) or not command or not all(isinstance(c, str) for c in command):
            raise ValueError(f"mcp.{name}.command: local server needs a non-empty list of strings")
        if "url" in cfg:
            raise ValueError(f"mcp.{name}: local server cannot have 'url'")
        out = {"type": "stdio", "command": command[0]}
        if command[1:]:
            out["args"] = command[1:]
    else:
        raise ValueError(f"mcp.{name}.type: unknown transport {kind!r}")
    if "env" in cfg and "environment" in cfg:
        raise ValueError(f"mcp.{name}: both 'env' and 'environment' given")
    for key in ("env", "environment"):
        if key in cfg:
            if not isinstance(cfg[key], dict):
                raise ValueError(f"mcp.{name}.{key}: expected an object")
            if kind == "remote":
                raise ValueError(f"mcp.{name}.{key}: not valid on a remote server")
            out["env"] = {k: _env_value(name, f"{key}.{k}", v) for k, v in cfg[key].items()}
    if "enabled" in cfg:
        if not isinstance(cfg["enabled"], bool):
            raise ValueError(f"mcp.{name}.enabled: expected a boolean")
        out["enabled"] = cfg["enabled"]
    if "oauth" in cfg:
        out["oauth"] = _oauth(name, cfg["oauth"])
    return out


def convert(opencode_mcp: dict) -> dict:
    """The omp mcp.json document for an opencode `mcp` block. Pure; server order is kept."""
    return {
        "$schema": SCHEMA_URL,
        "mcpServers": {name: _server(name, cfg) for name, cfg in opencode_mcp.items()},
    }


def merge(generated: dict, existing: dict) -> tuple[dict, list[str]]:
    """Add generated servers whose name is absent; never modify an existing entry."""
    merged = copy.deepcopy(existing)
    changes: list[str] = []
    if "$schema" not in merged:
        merged["$schema"] = generated["$schema"]
    servers = merged.setdefault("mcpServers", {})
    if not isinstance(servers, dict):
        raise ValueError(f"'mcpServers' must be an object, got {type(servers).__name__}")
    for name, cfg in generated["mcpServers"].items():
        if name in servers:
            if servers[name] != cfg:
                changes.append(f"kept existing {name} (differs from generated)")
        else:
            servers[name] = copy.deepcopy(cfg)
            changes.append(f"added {name}")
    return merged, changes


def load_object(path: Path) -> dict:
    data = json.loads(path.read_text())
    if not isinstance(data, dict):
        raise ValueError(f"{path}: expected a JSON object at top level, got {type(data).__name__}")
    return data


def main(argv: list[str]) -> int:
    if len(argv) != 4 or argv[1] != "merge":
        print(__doc__, file=sys.stderr)
        return 2
    generated_path, target = Path(argv[2]), Path(argv[3])
    generated = load_object(generated_path)
    if target.exists():
        current = load_object(target)  # raises on a malformed target before any write
    else:
        current = None
    merged, changes = merge(generated, current or {})
    if current is not None and merged == current:
        print(f"  merged {generated_path.name} into {target}")
        print("    (no changes)")
        return 0
    if current is None:
        print(f"  creating {target}")
    else:
        backup = target.with_name(f"{target.name}.bak-{datetime.now():%Y%m%d-%H%M%S}")
        shutil.copy2(target, backup)
        print(f"  backed up {target} -> {backup}")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(merged, indent=2) + "\n")
    print(f"  merged {generated_path.name} into {target}")
    for line in changes:
        print(f"    {line}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
