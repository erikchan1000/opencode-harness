def test_disjoint_slice_id_blocks_merge_and_plan(tmp_path):
    # SKILL.omp.md Phase 1: each research slice numbers from its own id block.
    a = write_json(tmp_path / "a.json", [finding("F101", touches=["a.py"]), finding("F102", touches=["b.py"])])
    b = write_json(tmp_path / "b.json", [finding("F201", touches=["a.py"])])
    out = tmp_path / "out.json"
    r = run("--findings-json", a, b, "--format", "json", "--output", str(out), "--title", "t")
    assert r.returncode == 0, r.stderr
    doc = json.loads(out.read_text())
    ids = [f["id"] for w in doc["waves"] for f in w["findings"]]
    assert sorted(ids) == ["F101", "F102", "F201"]
    # cross-slice ordering comes from the touches_files overlap on a.py: F101 and F201 never share a wave
    waves = [[f["id"] for f in w["findings"]] for w in doc["waves"]]
    assert not any({"F101", "F201"} <= set(w) for w in waves)


