def finding(fid, severity="high", depends_on=(), touches=(), status=None, title=None):
    doc = {
        "id": fid,
        "severity": severity,
        "area": "area",
        "title": title or f"Title {fid}",
        "evidence": [{"file": f"src/{fid.lower()}.py", "lines": "1-5"}],
        "depends_on": list(depends_on),
        "touches_files": list(touches),
        "root_cause": "rc",
        "fix_sketch": "fix",
        "test_sketch": "test",
    }
    if status is not None:
        doc["status"] = status
    return doc


def write_json(path: Path, findings) -> str:
    path.write_text(json.dumps({"findings": findings}))
    return str(path)


def run(*args):
    return subprocess.run([sys.executable, str(SCRIPT), *args], capture_output=True, text=True)


def md_table(rows):
    lines = [
        "| ID | Severity | Area | Title | File:Line | Depends on | Touches files | Status |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for fid, sev, title, deps, files, status in rows:
        lines.append(f"| {fid} | {sev} | area | {title} | src/{fid.lower()}.py:1-5 | {deps} | {files} | {status} |")
    return "\n".join(lines) + "\n"


def strip_timestamp(text: str) -> str:
    return "\n".join(l for l in text.splitlines() if not l.startswith("Generated by build_pipelines.py at"))


def test_two_files_merged_in_argument_order(tmp_path):
    a = write_json(tmp_path / "a.json", [finding("F01", touches=["a.py"])])
    b = write_json(tmp_path / "b.json", [finding("F02", depends_on=["F01"], touches=["b.py"])])
    out = tmp_path / "out.json"
    r = run("--findings-json", a, b, "--format", "json", "--output", str(out), "--title", "t")
    assert r.returncode == 0, r.stderr
    doc = json.loads(out.read_text())
    assert [[f["id"] for f in w["findings"]] for w in doc["waves"]] == [["F01"], ["F02"]]
    assert doc["waves"][1]["findings"][0]["depends_on"] == ["F01"]
    assert out.read_text().endswith("}\n")


def test_json_matches_markdown_wave_plan(tmp_path):
    rows = [
        ("F01", "high", "One", "", "x.py", ""),
        ("F02", "medium", "Two", "", "x.py", ""),
        ("F03", "low", "Three", "F01", "z.py", ""),
        ("F04", "critical", "Four", "", "w.py", ""),
    ]
    md = tmp_path / "findings.md"
    md.write_text(md_table(rows))
    js = write_json(
        tmp_path / "f.json",
        [
            finding("F01", "high", touches=["x.py"], title="One"),
            finding("F02", "medium", touches=["x.py"], title="Two"),
            finding("F03", "low", depends_on=["F01"], touches=["z.py"], title="Three"),
            finding("F04", "critical", touches=["w.py"], title="Four"),
        ],
    )
    out_md, out_js = tmp_path / "p.md", tmp_path / "p.json"
    r1 = run("--findings", str(md), "--output", str(out_md), "--title", "t")
    r2 = run("--findings-json", js, "--format", "json", "--output", str(out_js), "--title", "t")
    assert r1.returncode == 0 and r2.returncode == 0
    wave_lines = [l for l in r1.stdout.splitlines() if l.startswith("  Wave ")]
    doc = json.loads(out_js.read_text())
    json_lines = [f"  Wave {w['wave']}: " + ", ".join(f["id"] for f in w["findings"]) for w in doc["waves"]]
    assert wave_lines == json_lines
    # F01/F02 share x.py -> F02 deferred behind F01 by file conflict
    assert [w["wave"] for w in doc["waves"] if any(f["id"] == "F02" for f in w["findings"])] == [2]


